def build_hat():
    verts, uvs, norms, faces = [], [], [], []

    def cell_uv(c):
        u0, u1 = (4 * c + 0.5) / 16, (4 * c + 3.5) / 16
        vt, vb = 1 - 0.5 / 16, 1 - 3.5 / 16
        return u0, u1, vb, vt

    def quad(pts, normal, cell):
        u0, u1, vb, vt = cell_uv(cell)
        base_v = len(verts)
        base_t = len(uvs)
        verts.extend(pts)
        uvs.extend([(u0, vb), (u1, vb), (u1, vt), (u0, vt)])
        norms.append(normal)
        ni = len(norms)
        faces.append(["%d/%d/%d" % (base_v + i + 1, base_t + i + 1, ni)
                      for i in range(4)])

    def box(x0, x1, y0, y1, z0, z1, top, bottom, side):
        quad([(x0, y1, z1), (x1, y1, z1), (x1, y1, z0), (x0, y1, z0)], (0, 1, 0), top)
        quad([(x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1)], (0, -1, 0), bottom)
        quad([(x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)], (0, 0, 1), side)
        quad([(x1, y0, z0), (x0, y0, z0), (x0, y1, z0), (x1, y1, z0)], (0, 0, -1), side)
        quad([(x1, y0, z1), (x1, y0, z0), (x1, y1, z0), (x1, y1, z1)], (1, 0, 0), side)
        quad([(x0, y0, z0), (x0, y0, z1), (x0, y1, z1), (x0, y1, z0)], (-1, 0, 0), side)

    box(-0.36, 0.36, 0.0, 0.035, -0.36, 0.36, 0, 1, 1)      # brim
    box(-0.24, 0.24, 0.035, 0.19, -0.24, 0.24, 3, 1, 2)     # crown + band
    box(-0.19, 0.19, 0.19, 0.225, -0.19, 0.19, 3, 3, 3)     # pinched top

    with open(os.path.join(MODELS, PREFIX + "hat.obj"), "w", newline="\n") as fh:
        fh.write("# Expedition Assets - safari hat, generated by dev/build_assets.py\n")
        fh.write("o hat\n")
        for v in verts:
            fh.write("v %.4f %.4f %.4f\n" % v)
        for t in uvs:
            fh.write("vt %.5f %.5f\n" % t)
        for n in norms:
            fh.write("vn %d %d %d\n" % n)
        fh.write("usemtl hat\ns off\n")
        for f in faces:
            fh.write("f " + " ".join(f) + "\n")

    img = Image.new("RGBA", (16, 16), (214, 191, 146, 255))
    rnd = random.Random(7)
    cells = [(205, 180, 135), (168, 143, 99), (214, 191, 146), (224, 203, 160)]
    for c, col in enumerate(cells):
        for y in range(4):
            for x in range(4):
                j = rnd.randint(-6, 6)
                rgb = tuple(max(0, min(255, k + j)) for k in col)
                if c == 2 and y == 3:
                    rgb = (107, 74, 46)
                img.putpixel((4 * c + x, y), rgb + (255,))
    img.save(os.path.join(TEXTURES, PREFIX + "hat.png"))
    print("model hat + texture")


