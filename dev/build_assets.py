# ---------------------------------------------------------------------------
# 1. OBJ conversion (Kenney units -> Luanti node units)
# ---------------------------------------------------------------------------
# Luanti node meshes use 1 unit = 1 node, centred on the node centre, so the
# floor of a node is at y = -0.5.  Kenney models stand on y = 0 and are tiny.

def read_obj(path):
    verts, uvs, norms, faces = [], [], [], []
    with open(path, "r", encoding="utf-8", errors="ignore") as fh:
        for raw in fh:
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            tag = parts[0]
            if tag == "v":
                verts.append(tuple(float(p) for p in parts[1:4]))
            elif tag == "vt":
                uvs.append(tuple(float(p) for p in parts[1:3]))
            elif tag == "vn":
                norms.append(tuple(float(p) for p in parts[1:4]))
            elif tag == "f":
                faces.append(parts[1:])
    return verts, uvs, norms, faces


def bounds(verts):
    xs, ys, zs = zip(*verts)
    return (min(xs), max(xs)), (min(ys), max(ys)), (min(zs), max(zs))


def write_obj(path, name, verts, uvs, norms, faces, header=""):
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# Expedition Assets - generated by dev/build_assets.py\n")
        if header:
            fh.write("# " + header + "\n")
        fh.write("o %s\n" % name)
        for v in verts:
            fh.write("v %.6f %.6f %.6f\n" % v)
        for t in uvs:
            fh.write("vt %.6f %.6f\n" % t)
        for n in norms:
            fh.write("vn %.6f %.6f %.6f\n" % n)
        fh.write("usemtl colormap\ns off\n")
        for f in faces:
            fh.write("f " + " ".join(f) + "\n")


def convert(src_names, out_name, size=None, scale=None, z_shift=0.0):
    """Convert one or more Kenney OBJ files sharing one transform.

    size  = (width_x, height_y, depth_z) target size in nodes (non-uniform)
    scale = uniform scale factor
    """
    loaded = {n: read_obj(os.path.join(SRC, n + ".obj")) for n in src_names}
    allv = [v for d in loaded.values() for v in d[0]]
    (x0, x1), (y0, y1), (z0, z1) = bounds(allv)
    if size:
        sx = size[0] / (x1 - x0)
        sy = size[1] / (y1 - y0)
        sz = size[2] / (z1 - z0)
    else:
        sx = sy = sz = scale
    cx, cz = (x0 + x1) / 2, (z0 + z1) / 2
    for n, (verts, uvs, norms, faces) in loaded.items():
        nv = [((x - cx) * sx, (y - y0) * sy - 0.5, (z - cz) * sz + z_shift)
              for x, y, z in verts]
        nn = []
        for x, y, z in norms:
            a, b, c = x / sx, y / sy, z / sz
            l = math.sqrt(a * a + b * b + c * c) or 1.0
            nn.append((a / l, b / l, c / l))
        target = out_name if len(src_names) == 1 else out_name[n]
        write_obj(os.path.join(MODELS, PREFIX + target + ".obj"), target,
                  nv, uvs, nn, faces,
                  "Source model by Kenney (www.kenney.nl), CC0")
        (bx0, bx1), (by0, by1), (bz0, bz1) = bounds(nv)
        print("model %-16s x[%.2f %.2f] y[%.2f %.2f] z[%.2f %.2f]"
              % (target, bx0, bx1, by0, by1, bz0, bz1))


def build_models():
    # Expedition box: exactly one node.  Both states share one transform so
    # the lid hinge lines up when the node is swapped.
    convert(["box", "box-open"], {"box": "box", "box-open": "box_open"},
            scale=4.0)
    # Tents: 5 wide (x), ~3.4 high, 4 deep (z).  Shift by +0.5 on z so the
    # 4-node footprint lines up with node borders (z = -1 .. +2).
    convert(["tent", "tent-canvas"],
            {"tent": "tent", "tent-canvas": "tent_canvas"},
            size=(5.0, 3.4, 4.0), z_shift=0.5)
    # Tools put down on the ground: ~0.75 nodes tall.
    for t in ("shovel", "axe", "pickaxe", "hammer", "hoe"):
        convert(["tool-" + t], "tool_" + t, scale=3.0)
    # Signposts: one node wide standing on the ground (~2 nodes tall).
    convert(["signpost", "signpost-single"],
            {"signpost": "signpost", "signpost-single": "signpost_single"},
            scale=4.5)


