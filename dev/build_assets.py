# characters whose colour gets a little per-pixel noise (cloth, hair, skin)
NOISY = set("hsvopcbtaHgGfFkCPVO")


def plaid(x, y):
    dx, dy = x % 4 == 0, y % 4 == 0
    if dx and dy:
        return (90, 12, 16)
    if dx or dy:
        return (128, 22, 26)
    if x % 4 == 2 and y % 4 == 2:
        return (214, 82, 70)
    return (184, 40, 44)


def mirror_rows(rows):
    return [r[::-1] for r in rows]


def paint(img, rect, spec, pal, rnd):
    x0, y0, w, h = rect
    rows = [spec * w] * h if isinstance(spec, str) and len(spec) == 1 else spec
    assert len(rows) == h, (rect, rows)
    for j, row in enumerate(rows):
        assert len(row) == w, (rect, row)
        for i, ch in enumerate(row):
            x, y = x0 + i, y0 + j
            if ch == "p":
                rgb = plaid(x, y)
            else:
                rgb = pal[ch]
            if ch in NOISY:
                n = rnd.randint(-7, 7)
                rgb = tuple(max(0, min(255, c + n)) for c in rgb)
            img.putpixel((x, y), tuple(rgb) + (255,))


def make_skin(name, pal, parts):
    rnd = random.Random(name)
    img = Image.new("RGBA", (64, 32), (0, 0, 0, 0))
    for layout, key in ((HEAD, "head"), (BODY, "body"), (ARM, "arm"), (LEG, "leg")):
        faces = parts[key]
        for face, rect in layout.items():
            spec = faces[face]
            if spec == "mirror:right":
                spec = mirror_rows(faces["right"])
            paint(img, rect, spec, pal, rnd)
    img.save(os.path.join(TEXTURES, PREFIX + "skin_" + name + ".png"))

    # 64x64 variant: copy the top half and mirror the right limbs to the left.
    big = Image.new("RGBA", (64, 64), (0, 0, 0, 0))
    big.paste(img, (0, 0))

    def limb(sx, sy, dx, dy):
        def crop(ox, oy, w, h):
            return img.crop((sx + ox, sy + oy, sx + ox + w, sy + oy + h)) \
                .transpose(Image.FLIP_LEFT_RIGHT)
        big.paste(crop(4, 0, 4, 4), (dx + 4, dy))        # top
        big.paste(crop(8, 0, 4, 4), (dx + 8, dy))        # bottom
        big.paste(crop(8, 4, 4, 12), (dx + 0, dy + 4))   # inner  <- src inner
        big.paste(crop(4, 4, 4, 12), (dx + 4, dy + 4))   # front
        big.paste(crop(0, 4, 4, 12), (dx + 8, dy + 4))   # outer  <- src outer
        big.paste(crop(12, 4, 4, 12), (dx + 12, dy + 4))  # back
    limb(0, 16, 16, 48)   # left leg
    limb(40, 16, 32, 48)  # left arm
    big.save(os.path.join(TEXTURES, PREFIX + "skin_" + name + "_64.png"))
    print("skin", name)


