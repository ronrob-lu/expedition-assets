SYMBOL_NAMES = {"-": "dash", "!": "excl", ".": "dot", "?": "qmark"}


def wood_background(seed):
    rnd = random.Random(seed)
    img = Image.new("RGBA", (16, 16))
    for y in range(16):
        band = (74, 48, 28) if y % 4 == 3 else (92, 60, 36)
        for x in range(16):
            j = rnd.randint(-6, 6)
            img.putpixel((x, y), tuple(max(0, c + j) for c in band) + (255,))
    return img


def build_letters():
    bg = wood_background(1)
    bg.save(os.path.join(TEXTURES, PREFIX + "letter_bg.png"))
    yellow, shade = (242, 196, 52, 255), (52, 32, 18, 255)
    for ch, glyph in FONT.items():
        rows = glyph.split("|")
        img = wood_background(ord(ch))
        ox, oy = 3, 1
        # drop shadow
        for j, row in enumerate(rows):
            for i, c in enumerate(row):
                if c == "#":
                    for dx in range(2):
                        for dy in range(2):
                            px, py = ox + i * 2 + dx + 1, oy + j * 2 + dy + 1
                            if px < 16 and py < 16:
                                img.putpixel((px, py), shade)
        for j, row in enumerate(rows):
            for i, c in enumerate(row):
                if c == "#":
                    for dx in range(2):
                        for dy in range(2):
                            img.putpixel((ox + i * 2 + dx, oy + j * 2 + dy), yellow)
        key = SYMBOL_NAMES.get(ch, ch.lower())
        img.save(os.path.join(TEXTURES, PREFIX + "letter_" + key + ".png"))
    print("letters:", len(FONT))


